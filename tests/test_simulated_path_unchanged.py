"""
The simulated bots must not notice that an order path was built beside them.

Stocks v5 is a sealed registration running on twelve simulated bots. On
2026-11-16 stock_bot.py gained a mode that sends real orders (broker paper,
and the same path for live). The condition on that work was that a bot started
the way the twelve are started does, to the byte, what it did before.

Two tests hold it to that. Both drive the real main() through the same seven
ticks (a buy, a hold, a take-profit sell, a flat tick, a second buy, a stop
loss, a closed market) with only the edges replaced, and collect everything
the bot produces: the state file after every tick, the ledger, every log
line, every notification, every signal row and every sleep.

  1. Against a recording. GOLDEN below is what the code at commit 7d75a32 (the
     last one before the order path) produced. It was generated by running
     that file, not written by hand.
  2. Against the old file itself, when git can still produce it. This is the
     stronger check and the one to trust if the two ever disagree; it is
     skipped, not failed, in a checkout without that commit.

While it runs, the broker is a tripwire: any call to the venue, the trading
client or the order journal fails the test.
"""
import json
import logging
import os
import subprocess
import sys
import types
from datetime import datetime, timedelta, timezone

import pytest

DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, DIR)

from utils import watchdog  # noqa: E402
from stock_bot_harness import (FakeSignalLog, FakeWatchdog, StopLoop,  # noqa: E402
                               hourly_bars, load_stock_bot)

BEFORE = "7d75a32"          # last commit before the order path was built

# Everything the scenario depends on is pinned, so nothing left in the
# environment by .env or by another test can change the recording.
ENV = {
    "TRADE_AMOUNT_USD": "100", "ALPACA_BASE_URL": "https://paper-api.alpaca.markets",
    "STOCK_SMA_SHORT_WINDOW": "10", "STOCK_SMA_LONG_WINDOW": "30",
    "STOCK_STOP_LOSS_PERCENT": "3.0", "STOCK_TAKE_PROFIT_PERCENT": "5.0",
    "STOCK_RSI_BUY_MIN": "40", "STOCK_RSI_BUY_MAX": "70",
    "STOCK_RSI_OVERSOLD": "35", "STOCK_RSI_OVERBOUGHT": "65",
    "STOCK_LOOP_INTERVAL_SEC": "60", "STOCK_CANDLE_BARS": "100",
    "STOCK_TRAILING_STOP_PERCENT": "0.0",
    "STOCK_TRAILING_STOP_ACTIVATION_PERCENT": "0.0",
    "STOCK_MIN_VOLUME_RATIO": "0.0", "STOCK_COOLDOWN_HOURS_AFTER_LOSS": "0.0",
    "STOCK_TREND_GATE_DAYS": "50", "STOCK_TREND_GATE_SYMBOL": "SPY",
    "STOCK_WATCHDOG_TIMEOUT_SEC": "600",
}
UNSET = ("ZZTEST_SMA_SHORT_WINDOW", "ZZTEST_SMA_LONG_WINDOW", "ZZTEST_STOP_LOSS_PERCENT",
         "ZZTEST_TAKE_PROFIT_PERCENT", "ZZTEST_TRAILING_STOP_PERCENT",
         "ZZTEST_TRAILING_STOP_ACTIVATION_PERCENT", "ZZTEST_COOLDOWN_HOURS_AFTER_LOSS",
         "ZZTEST_RSI_OVERSOLD", "ZZTEST_RSI_OVERBOUGHT")

TICKS = [
    {"price": 100.60, "enter": True},       # buy
    {"price": 101.00},                      # hold
    {"price": 106.00},                      # +5.4%: take profit
    {"price": 100.00},                      # flat, no signal
    {"price": 100.00, "enter": True},       # buy again
    {"price": 96.90},                       # -3.1%: stop loss
    {"open": False},                        # market closed
]


def run_scenario(monkeypatch, tmp_path, path=None, name="stock_bot_under_test"):
    """Drive one stock_bot.py through TICKS in simulated mode and return
    everything it produced."""
    for key in UNSET:
        monkeypatch.delenv(key, raising=False)
    bot = load_stock_bot(monkeypatch, path=path, name=name, env=ENV)
    work = tmp_path / name
    work.mkdir()
    bot.STATE_PATH = str(work / "state_stock_zztest_paper.json")
    bot.TRADES_PATH = str(work / "completed_trades_stock_zztest_paper.csv")
    bot._SHARED_STATE = None

    tick = {"n": 0}
    out = {"states": [], "naps": [], "notifications": [], "logs": []}

    class Clock(datetime):
        calls = 0

        @classmethod
        def now(cls, tz=None):
            cls.calls += 1
            return (datetime(2026, 11, 16, 15, 0, tzinfo=timezone.utc)
                    + timedelta(seconds=cls.calls))

    def tripwire(*args, **kwargs):
        raise AssertionError("a simulated bot reached for the broker")

    def current():
        return TICKS[min(tick["n"], len(TICKS) - 1)]

    def fake_sleep(seconds):
        out["naps"].append(seconds)
        try:
            with open(bot.STATE_PATH) as handle:
                out["states"].append(handle.read())
        except FileNotFoundError:
            out["states"].append(None)
        tick["n"] += 1
        if tick["n"] >= len(TICKS):
            raise StopLoop()

    class Capture(logging.Handler):
        def emit(self, record):
            out["logs"].append(f"{record.levelname} {record.getMessage()}")

    handler = Capture()
    bot.log.addHandler(handler)
    bot.log.setLevel(logging.INFO)
    signals, dog = FakeSignalLog(), FakeWatchdog()
    from utils.market_gate import GateState
    gate = GateState(False, 760.0, 750.0, session="2026-11-13")
    real_indicators = bot.compute_indicators

    monkeypatch.setattr(bot, "datetime", Clock)
    monkeypatch.setattr(bot, "time", types.SimpleNamespace(sleep=fake_sleep))
    monkeypatch.setattr(bot, "is_market_open", lambda: current().get("open", True))
    monkeypatch.setattr(bot, "minutes_until_open", lambda: 45)
    monkeypatch.setattr(bot, "fetch_bars", lambda ticker, n: hourly_bars())
    monkeypatch.setattr(bot, "compute_indicators",
                        lambda frame: {**real_indicators(frame), "price": current()["price"]})
    monkeypatch.setattr(bot, "entry_signal",
                        lambda ind: (True, "test entry") if current().get("enter") else (False, ""))
    monkeypatch.setattr(bot, "trend_gate",
                        lambda: types.SimpleNamespace(state=lambda: gate))
    monkeypatch.setattr(bot, "signal_logger", lambda: signals)
    monkeypatch.setattr(bot, "_notify",
                        lambda *a, **k: out["notifications"].append([list(a), k]))
    monkeypatch.setattr(bot, "venue", tripwire)
    monkeypatch.setattr(bot, "_trading_client", tripwire)
    if hasattr(bot, "broker"):
        monkeypatch.setattr(bot, "broker", tripwire)
    monkeypatch.setattr(watchdog, "start", lambda *a, **k: dog)

    try:
        with pytest.raises(StopLoop):
            bot.main()
    finally:
        bot.log.removeHandler(handler)

    with open(bot.TRADES_PATH) as handle:
        out["ledger"] = handle.read()
    out["signals"] = [[t, c, p, json.dumps(d, sort_keys=True)] for t, c, p, d in signals.rows]
    out["watchdog"] = dog.allowed
    out["files"] = sorted(os.listdir(work))
    # The only thing allowed to differ between two copies of the file is where
    # the copy sits on disk.
    out["logs"] = [line.replace(str(work), "<work>") for line in out["logs"]]
    return out


def test_the_scenario_really_trades(monkeypatch, tmp_path):
    """Guard on the tests below: a scenario in which nothing happened would
    match anything."""
    out = run_scenario(monkeypatch, tmp_path)
    assert out["ledger"].count("\n") == 3                      # header + two trades
    assert "Take Profit Triggered" in out["ledger"]
    assert "Stop Loss Triggered" in out["ledger"]
    assert [n[0][0] for n in out["notifications"]] == ["BUY", "SELL", "BUY", "SELL"]
    assert out["naps"] == [60, 60, 60, 60, 60, 60, 30 * 60]


def test_simulated_bot_matches_the_recording_from_before_the_order_path(monkeypatch, tmp_path):
    out = run_scenario(monkeypatch, tmp_path)
    with open(os.path.join(os.path.dirname(__file__), "simulated_golden.json")) as handle:
        golden = json.load(handle)
    for key in golden:
        assert out[key] == golden[key], f"simulated bot changed: {key}"
    assert set(out) == set(golden)


def test_simulated_bot_matches_the_old_file_itself(monkeypatch, tmp_path):
    old = subprocess.run(["git", "show", f"{BEFORE}:stock_bot.py"], cwd=DIR,
                         capture_output=True, text=True)
    if old.returncode != 0:
        pytest.skip(f"commit {BEFORE} is not in this checkout")
    old_dir = tmp_path / "before"
    old_dir.mkdir()
    (old_dir / "stock_bot.py").write_text(old.stdout)

    before = run_scenario(monkeypatch, tmp_path, path=str(old_dir / "stock_bot.py"),
                          name="stock_bot_before")
    after = run_scenario(monkeypatch, tmp_path, name="stock_bot_after")
    for key in before:
        assert after[key] == before[key], f"simulated bot changed: {key}"


def test_a_simulated_bots_file_names_are_what_they_were(monkeypatch):
    bot = load_stock_bot(monkeypatch)
    assert bot.MODE == "PAPER" and not bot.SENDS_ORDERS and not bot.BROKER_PAPER
    assert bot.STATE_PATH == os.path.join(DIR, "state_stock_zztest_paper.json")
    assert bot.TRADES_PATH == os.path.join(DIR, "completed_trades_stock_zztest_paper.csv")
    assert bot.log_path == os.path.join(DIR, "logs", "stock_zztest.log")
    assert bot.SIGNAL_LOG == ("stock-ZZTEST", "logs")
    assert bot.TRADE_FIELDNAMES == [
        "ticker", "entry_time", "exit_time", "entry_price", "exit_price",
        "entry_reason", "exit_reason", "gross_pct", "net_pct",
        "pnl_usd", "shares", "mode"]


@pytest.mark.parametrize("name", ["STOCK_EXECUTION", "STOCK_EXECUTION_MODE", "BROKER_PAPER",
                                  "STOCK_BROKER_PAPER", "SENDS_ORDERS"])
def test_no_environment_variable_turns_a_simulated_bot_into_an_order_sender(monkeypatch, name):
    """`pm2 restart --update-env` and .env both reach every bot. Neither may
    be able to carry this."""
    bot = load_stock_bot(monkeypatch, env={name: "BROKER_PAPER", name + "_X": "True"})
    assert not bot.SENDS_ORDERS and bot.MODE == "PAPER"
    with open(os.path.join(DIR, "stock_bot.py")) as handle:
        source = handle.read()
    assert "execution_mode.REQUESTED" in source
    for line in source.splitlines():
        if "BROKER_PAPER" in line and "getenv" in line:
            raise AssertionError(f"broker paper is read from the environment: {line.strip()}")
